"""
Two-factor authentication recovery code utilities.

Recovery codes allow a user to regain access to their account when they cannot
use their regular two-factor authentication method (e.g. lost authenticator
device).  Each code is single-use: once a code has been consumed it is removed
from the stored set and can never be used again.

Usage example::

    # --- at account setup time ---
    codes = generate_recovery_codes()          # show these to the user once
    stored = [hash_recovery_code(c) for c in codes]
    # persist `stored` in the database

    # --- at login time ---
    provided = input("Enter a recovery code: ").strip()
    ok, stored = verify_recovery_code(stored, provided)
    if ok:
        print("Access granted.")
    else:
        print("Invalid or already-used recovery code.")
"""

import hashlib
import os
import secrets
from typing import List, Tuple


_CODE_GROUPS: int = 4       # number of hyphen-separated groups
_GROUP_LENGTH: int = 5      # characters per group
_DEFAULT_COUNT: int = 10    # recovery codes generated by default


def generate_recovery_codes(count: int = _DEFAULT_COUNT) -> List[str]:
    """Return *count* random, URL-safe recovery codes.

    Each code has the form ``XXXXX-XXXXX-XXXXX-XXXXX`` where every character
    is a random alphanumeric character (upper-case letters and digits only, to
    avoid ambiguous characters like ``0``/``O`` or ``1``/``l``).

    Args:
        count: Number of codes to generate.  Defaults to 10.

    Returns:
        A list of plain-text recovery codes that should be displayed to the
        user **once** and then discarded.  Only the hashed versions (see
        :func:`hash_recovery_code`) should be stored.
    """
    # Excludes visually ambiguous characters: '0'/'O', '1'/'I'/'l'
    alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    codes: List[str] = []
    for _ in range(count):
        groups = [
            "".join(secrets.choice(alphabet) for _ in range(_GROUP_LENGTH))
            for _ in range(_CODE_GROUPS)
        ]
        codes.append("-".join(groups))
    return codes


def hash_recovery_code(code: str) -> str:
    """Return a hex-encoded SHA-256 hash of *code* (normalised to upper-case).

    A random 16-byte salt is prepended to the hash input so that two identical
    codes produce different stored values.  The salt is stored as the first 32
    hex characters of the returned string, followed by the 64-character hash.

    Args:
        code: Plain-text recovery code (e.g. ``"ABCDE-FGHJK-MNPQR-STUVW"``).

    Returns:
        A 96-character hex string ``<salt_hex><hash_hex>`` suitable for
        persistent storage.
    """
    salt = os.urandom(16)
    normalised = code.strip().upper().encode("utf-8")
    digest = hashlib.sha256(salt + normalised).hexdigest()
    return salt.hex() + digest


def _check_code(stored_hash: str, candidate: str) -> bool:
    """Return True if *candidate* matches *stored_hash*."""
    if len(stored_hash) != 96:
        return False
    salt = bytes.fromhex(stored_hash[:32])
    expected_digest = stored_hash[32:]
    normalised = candidate.strip().upper().encode("utf-8")
    actual_digest = hashlib.sha256(salt + normalised).hexdigest()
    return secrets.compare_digest(actual_digest, expected_digest)


def verify_recovery_code(
    stored_hashes: List[str],
    provided_code: str,
) -> Tuple[bool, List[str]]:
    """Verify *provided_code* against the list of stored hashed recovery codes.

    If the code is valid it is **removed** from the returned list (single-use
    semantics).  The caller is responsible for persisting the updated list.

    Args:
        stored_hashes: Current list of hashed recovery codes as returned by
            :func:`hash_recovery_code`.
        provided_code: Plain-text code supplied by the user.

    Returns:
        A ``(success, updated_hashes)`` tuple where *success* is ``True`` when
        the code matched and *updated_hashes* is the remaining stored hashes
        after consuming the matched code.
    """
    remaining: List[str] = list(stored_hashes)
    for i, stored in enumerate(remaining):
        if _check_code(stored, provided_code):
            updated = remaining[:i] + remaining[i + 1:]
            return True, updated
    return False, remaining
